// Builds a CSS selector for a recorded element. Pure on purpose: the content script passes DOM nodes that satisfy
// SelectorNode, and tests pass plain objects with a fake match counter, so no DOM library is needed.

export interface SelectorNode {
  /** Lowercase tag name, e.g. "button". */
  tagName: string;
  /** Position among same-tag siblings, 1-based. */
  typeIndex: number;
  getAttribute(name: string): string | null;
  parent: SelectorNode | null;
}

// Attributes that usually identify an element across page loads, in order of preference after id.
const STABLE_ATTRIBUTES = ['data-testid', 'data-test', 'name', 'aria-label'] as const;
const MAX_PATH_DEPTH = 8;
const MAX_SELECTOR_CHARS = 500;

const AUTO_GENERATED_ID_PATTERN = /^\d|\d{4,}|^[a-f0-9]{8,}$|^(:r|ember|react|sc-|css-|ng-|headlessui|radix|mui-)/i;

/** Framework and hash-looking ids change between builds or renders, so they are not used as anchors. */
export function isAutoGeneratedId(id: string): boolean {
  return id.length === 0 || id.length > 64 || AUTO_GENERATED_ID_PATTERN.test(id);
}

export function escapeCssIdentifier(value: string): string {
  return value.replace(/[^a-zA-Z0-9_-]/g, char => `\\${char}`);
}

export function escapeAttributeValue(value: string): string {
  return value.replace(/["\\]/g, char => `\\${char}`).slice(0, 200);
}

/**
 * Returns the most specific selector that matches exactly one element: a stable id, then a stable attribute,
 * then a short nth-of-type path that stops at the nearest unique id. `countMatches` runs the selector on the page.
 */
export function buildElementSelector(node: SelectorNode, countMatches: (selector: string) => number): string {
  const byId = idSelector(node, countMatches);
  if (byId) return byId;

  for (const attribute of STABLE_ATTRIBUTES) {
    const value = node.getAttribute(attribute);
    if (!value) continue;
    const selector = `${node.tagName}[${attribute}="${escapeAttributeValue(value)}"]`;
    if (countMatches(selector) === 1) return selector;
  }

  return pathSelector(node, countMatches);
}

function idSelector(node: SelectorNode, countMatches: (selector: string) => number): string | null {
  const id = node.getAttribute('id') ?? '';
  if (isAutoGeneratedId(id)) return null;
  const selector = `#${escapeCssIdentifier(id)}`;
  return countMatches(selector) === 1 ? selector : null;
}

function pathSelector(node: SelectorNode, countMatches: (selector: string) => number): string {
  const parts: string[] = [];
  let current: SelectorNode | null = node;
  while (current && current.tagName !== 'html' && parts.length < MAX_PATH_DEPTH) {
    const anchor = parts.length > 0 ? idSelector(current, countMatches) : null;
    if (anchor) {
      parts.unshift(anchor);
      break;
    }
    parts.unshift(current.typeIndex > 1 ? `${current.tagName}:nth-of-type(${current.typeIndex})` : current.tagName);
    current = current.parent;
  }
  return parts.join(' > ').slice(0, MAX_SELECTOR_CHARS);
}
