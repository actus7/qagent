import { describe, expect, it } from 'vitest';
import { buildElementSelector, isAutoGeneratedId, type SelectorNode } from '@extension/shared';

interface FakeNode extends SelectorNode {
  attributes: Record<string, string>;
}

function node(tagName: string, attributes: Record<string, string>, parent: FakeNode | null, typeIndex = 1): FakeNode {
  return {
    tagName,
    typeIndex,
    attributes,
    getAttribute: name => attributes[name] ?? null,
    parent,
  };
}

/** A page where `countMatches` answers from a fixed list of selectors that match exactly one element. */
const uniqueOn = (selectors: string[]) => (selector: string) => (selectors.includes(selector) ? 1 : 0);

describe('isAutoGeneratedId', () => {
  it('treats framework and hash-like ids as unstable', () => {
    expect(isAutoGeneratedId('')).toBe(true);
    expect(isAutoGeneratedId(':r1f:')).toBe(true);
    expect(isAutoGeneratedId('react-select-3-input')).toBe(true);
    expect(isAutoGeneratedId('field-20391')).toBe(true);
    expect(isAutoGeneratedId('9lives')).toBe(true);
    expect(isAutoGeneratedId('3f9a2b7c1d')).toBe(true);
  });

  it('keeps human-written ids', () => {
    expect(isAutoGeneratedId('checkout-submit')).toBe(false);
    expect(isAutoGeneratedId('email')).toBe(false);
  });
});

describe('buildElementSelector', () => {
  it('uses a stable id when it matches exactly one element', () => {
    const button = node('button', { id: 'go' }, null);

    expect(buildElementSelector(button, uniqueOn(['#go']))).toBe('#go');
  });

  it('skips an id that is auto-generated or not unique', () => {
    const button = node('button', { id: 'react-3', 'data-testid': 'pay' }, null);
    const selector = buildElementSelector(button, uniqueOn(['button[data-testid="pay"]']));

    expect(selector).toBe('button[data-testid="pay"]');
  });

  it('falls back to a unique name or aria-label when the id is not usable', () => {
    const input = node('input', { name: 'email', 'aria-label': 'Email' }, null);

    expect(buildElementSelector(input, uniqueOn(['input[name="email"]']))).toBe('input[name="email"]');
    expect(buildElementSelector(input, uniqueOn(['input[aria-label="Email"]']))).toBe('input[aria-label="Email"]');
  });

  it('builds a short nth-of-type path that stops at the nearest unique ancestor id', () => {
    const main = node('main', { id: 'content' }, null);
    const list = node('div', {}, main);
    const row = node('div', {}, list, 3);
    const button = node('button', {}, row, 2);

    expect(buildElementSelector(button, uniqueOn(['#content']))).toBe(
      '#content > div > div:nth-of-type(3) > button:nth-of-type(2)',
    );
  });

  it('escapes quotes in attribute values', () => {
    const button = node('button', { 'data-testid': 'say "hi"' }, null);

    expect(buildElementSelector(button, uniqueOn(['button[data-testid="say \\"hi\\""]']))).toBe(
      'button[data-testid="say \\"hi\\""]',
    );
  });
});
